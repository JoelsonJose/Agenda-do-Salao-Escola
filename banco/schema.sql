-- BANCO PADRÃO: H2 Database (In-Memory / File-based)
-- COMPATIBILIDADE: PostgreSQL / Azure SQL Database (SQL Server)
-- =====================================================================
-- Este script define o schema relacional da aplicação. Ele é idempotente
-- e pode ser executado múltiplas vezes de forma controlada.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. TABELA: servicos
-- Representa os procedimentos oferecidos pelo Salão-Escola.
-- Regra de Negócio: Duração obrigatória entre 15 e 240 minutos.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    duracao_minutos INT NOT NULL,
    CONSTRAINT chk_servico_duracao CHECK (duracao_minutos >= 15 AND duracao_minutos <= 240)
);

-- ---------------------------------------------------------------------
-- 2. TABELA: profissionais
-- Representa as cabeleireiras e profissionais fictícios do salão.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS profissionais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- 3. TABELA: agendamentos
-- Registra as marcações de clientes com um serviço e profissional.
-- Regras de Integridade:
--   - FKs obrigatórias para servicos e profissionais (impede dados órfãos).
--   - CHECK: data_hora_fim > data_hora_inicio (impede intervalos nulos ou invertidos).
--   - CHECK: status restrito a 'ATIVO' ou 'CANCELADO'.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente VARCHAR(100) NOT NULL,
    servico_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    data_hora_inicio TIMESTAMP NOT NULL,
    data_hora_fim TIMESTAMP NOT NULL,
    status VARCHAR(20) DEFAULT 'ATIVO' NOT NULL,
    
    -- Chaves Estrangeiras (Integridade Referencial)
    CONSTRAINT fk_agendamento_servico 
        FOREIGN KEY (servico_id) REFERENCES servicos(id) 
        ON DELETE RESTRICT,
        
    CONSTRAINT fk_agendamento_profissional 
        FOREIGN KEY (profissional_id) REFERENCES profissionais(id) 
        ON DELETE RESTRICT,
        
    -- Restrições de Validação de Dados (Check Constraints)
    CONSTRAINT chk_agendamento_horario 
        CHECK (data_hora_fim > data_hora_inicio),
        
    CONSTRAINT chk_agendamento_status 
        CHECK (status IN ('ATIVO', 'CANCELADO'))
);

-- ---------------------------------------------------------------------
-- 4. ÍNDICES DE PERFORMANCE
-- Otimizam a consulta diária por profissional e a verificação de conflitos.
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_agendamento_conflito 
    ON agendamentos (profissional_id, status, data_hora_inicio, data_hora_fim);

CREATE INDEX IF NOT EXISTS idx_agendamento_data 
    ON agendamentos (data_hora_inicio);

-- =====================================================================
-- NOTAS DE COMPATIBILIDADE E PORTABILIDADE ENTRE BANCOS:
-- =====================================================================
-- 1. H2 Database (Padrão adotado):
--    - Suporta sintaxe ANSI SQL `BIGINT GENERATED BY DEFAULT AS IDENTITY`.
--    - Suporta tipos `TIMESTAMP`, `CHECK` constraints e `CREATE INDEX IF NOT EXISTS`.
--
-- 2. PostgreSQL:
--    - `GENERATED BY DEFAULT AS IDENTITY` é nativo (ou `BIGSERIAL`).
--    - `TIMESTAMP` é equivalente a `TIMESTAMP WITHOUT TIME ZONE`.
--    - Sobreposição: O PostgreSQL suporta a extensão `btree_gist` com
--      restrição `EXCLUDE USING gist (profissional_id WITH =, tsrange(data_hora_inicio, data_hora_fim) WITH &&) WHERE (status = 'ATIVO')`.
--      No entanto, para manter portabilidade universal (H2 / Azure SQL / PostgreSQL),
--      a regra de sobreposição e retorno HTTP 409 é validada atomicamente na
--      camada de serviço da aplicação com controle transacional (ADR-006).
--
-- 3. Azure SQL (SQL Server / T-SQL):
--    - Para Azure SQL, a chave auto-incremento pode ser mapeada como `BIGINT IDENTITY(1,1) PRIMARY KEY`.
--    - O tipo `TIMESTAMP` do ANSI é mapeado para `DATETIME2(0)`.
--    - Cláusulas `CREATE TABLE IF NOT EXISTS` podem ser substituídas por:
--      `IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'servicos') CREATE TABLE servicos (...)`.
-- =====================================================================

